const { dropLocal } = require('./drop-local.cjs');
const { _electron } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { gzipSync } = require('node:zlib');

(async () => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'viewer-local-folder-'));
  let app;
  try {
    const root = path.join(temp, 'logs'), nested = path.join(root, 'nested');
    await fs.mkdir(nested, { recursive: true });
    await fs.writeFile(path.join(root, 'plain.log'), 'INFO folder-marker 中文\n');
    await fs.writeFile(path.join(root, 'signal.2026-10-15.001.gz'), gzipSync('ERROR folder-marker gzip 中文\n'));
    await fs.writeFile(path.join(nested, 'child.log'), 'INFO folder-marker child\n');
    await fs.writeFile(path.join(temp, 'outside.log'), 'outside');
    await fs.symlink(path.join(temp, 'outside.log'), path.join(root, 'outside-link.log'));
    app = await _electron.launch({ ...(process.env.VIEWER_TEST_EXECUTABLE ? { executablePath: process.env.VIEWER_TEST_EXECUTABLE, args: [] } : { args: ['.'] }), cwd: path.resolve(__dirname, '..'), env: { ...process.env, VIEWER_DATA_DIR: path.join(temp, 'config') } });
    await app.evaluate(({ dialog }, root) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [root] }); }, root);
    const page = await app.firstWindow(); const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await dropLocal(page, root);
    await page.getByLabel('本地路径', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('本地路径', { exact: true }).inputValue(), root);
    assert.equal(await page.getByLabel('文件来源', { exact: true }).inputValue(), 'local');
    assert.equal(await page.getByRole('button', { name: '↰ 上级目录', exact: true }).isDisabled(), true);
    assert.equal(await page.locator('.file-entry').filter({ hasText: 'outside-link' }).count(), 0);
    await page.getByPlaceholder('搜索全文关键词或正则表达式…').fill('folder-marker');
    await page.getByRole('button', { name: '搜索全文', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.batch-summary')?.textContent.includes('2/2'));
    assert.equal(await page.locator('.search-results .result').count(), 2);
    assert.equal(await page.getByLabel('搜索范围', { exact: true }).inputValue(), 'folder');
    await page.locator('.search-results .result').filter({ hasText: 'gzip 中文' }).click();
    await page.waitForFunction(() => document.querySelector('.document-bar')?.textContent.includes('1 行'));
    await page.waitForFunction(() => [...document.querySelectorAll('.line-content')].some(e => e.textContent.includes('gzip 中文')));
    assert.equal(await page.locator('.search-results .result').count(), 2);
    await page.locator('.file-entry').filter({ hasText: 'plain.log' }).click();
    await page.getByRole('button', { name: '查看', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.document-bar strong')?.textContent.endsWith('plain.log') && document.querySelector('.document-bar')?.textContent.includes('1 行'));
    await page.waitForFunction(() => [...document.querySelectorAll('.line-content')].some(e => e.textContent.includes('folder-marker 中文')));
    await page.getByLabel('文件名匹配', { exact: true }).fill('signal.2026-10-15.*.gz');
    assert.equal(await page.locator('.file-entry').filter({ hasText: 'plain.log' }).count(), 0);
    await page.getByRole('button', { name: '搜索全文', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.batch-summary')?.textContent.includes('1/1'));
    assert.equal(await page.locator('.search-results .result').count(), 1);
    await page.locator('.file-entry').filter({ hasText: 'nested' }).dblclick();
    await page.waitForFunction(dir => document.querySelector('input[aria-label="本地路径"]')?.value === dir, nested);
    await page.locator('.file-entry').filter({ hasText: 'child.log' }).dblclick();
    await page.waitForFunction(() => document.querySelector('.document-bar strong')?.textContent.endsWith('child.log') && document.querySelector('.document-bar')?.textContent.includes('1 行'));
    await page.getByRole('button', { name: '↰ 上级目录', exact: true }).click();
    await page.waitForFunction(dir => document.querySelector('input[aria-label="本地路径"]')?.value === dir, root);
    await fs.writeFile(path.join(root, 'new.log'), 'INFO folder-marker new\n');
    await page.getByRole('button', { name: '搜索全文', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.batch-summary')?.textContent.includes('3/3'));
    assert.equal(await page.locator('.search-results .result').count(), 3);
    const rejected = await page.evaluate(async outside => {
      try { await window.viewer.openLocalFile(outside); return false; } catch { return true; }
    }, path.join(temp, 'outside.log'));
    assert.equal(rejected, true);
    await page.getByLabel('文件来源', { exact: true }).selectOption('remote');
    await page.getByLabel('文件来源', { exact: true }).selectOption('local');
    assert.equal(await page.getByLabel('本地路径', { exact: true }).inputValue(), root);
    assert.equal(await page.getByLabel('本地路径', { exact: true }).inputValue(), root);
    await dropLocal(page, path.join(root, 'signal.2026-10-15.001.gz'));
    await page.waitForFunction(() => document.querySelector('.document-bar strong')?.textContent.endsWith('signal.2026-10-15.001.gz') && document.querySelector('.document-bar')?.textContent.includes('1 行'));
    assert.equal(await page.getByLabel('搜索范围', { exact: true }).inputValue(), 'current');
    await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, temp);
    await page.evaluate(() => window.viewer.chooseDirectory('extract'));
    await page.getByRole('button', { name: '解压', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.document-bar strong')?.textContent === 'signal.2026-10-15.001' && document.querySelector('.document-bar')?.textContent.includes('1 行'));
    await page.waitForFunction(() => [...document.querySelectorAll('.line-content')].some(e => e.textContent.includes('gzip 中文')));
    assert.equal(await page.locator('.document-bar strong').textContent(), 'signal.2026-10-15.001');
    assert.equal(await page.locator('.document-bar strong').getAttribute('title'), path.join(temp, 'logs', 'signal.2026-10-15.001') + '\n来源压缩文件：' + path.join(root, 'signal.2026-10-15.001.gz'));
    assert.match(await page.locator('.document-bar').textContent(), /本地解压 · signal\.2026-10-15\.001\.gz/);
    // Folder entry + wildcard leaves no single selection; extraction must still be available.
    await fs.writeFile(path.join(root, 'signal.2026-10-15.002.gz'), gzipSync('INFO batch-second 中文\n'));
    await fs.writeFile(path.join(root, 'signal.2026-10-15.broken.gz'), 'invalid gzip');
    await dropLocal(page, root);
    await page.getByLabel('文件名匹配', { exact: true }).fill('signal.2026-10-15.*.gz');
    assert.equal(await page.getByRole('button', { name: '解压匹配', exact: true }).isEnabled(), true);
    await page.getByRole('button', { name: '解压匹配文件（3）', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.statusbar')?.textContent.includes('成功 2 个') || document.body.textContent.includes('本地批量解压完成 · 成功 2 个 · 失败 1 个'));
    assert.equal(await page.getByLabel('打开解压文件', { exact: true }).locator('option').count(), 3);
    assert.match(await page.locator('.task-card').textContent(), /成功 2 · 失败 1/);
    assert.equal(await fs.readFile(path.join(root, 'signal.2026-10-15.broken.gz'), 'utf8'), 'invalid gzip');
    const extracted = await page.evaluate(() => window.viewer.settings());
    assert.equal(extracted.localPaths.length, 2);
    assert.equal(path.dirname(extracted.localPaths[0]), path.join(temp, 'logs'));
    assert.equal(path.dirname(extracted.localPaths[1]), path.join(temp, 'logs'));
    const reopened = await page.evaluate(file => window.viewer.openExtracted(file), extracted.localPaths[0]);
    assert.equal(reopened.archive, path.join(root, 'signal.2026-10-15.001.gz'));
    const contents = await Promise.all(extracted.localPaths.map(file => fs.readFile(file, 'utf8')));
    assert(contents.some(text => text.includes('batch-second 中文')));
    assert(contents.some(text => text.includes('gzip 中文')));
    const denied = await page.evaluate(async outside => {
      try { await window.viewer.extractLocalMatches(outside, '*'); return false; } catch { return true; }
    }, temp);
    assert.equal(denied, true);
    await page.getByLabel('文件名匹配', { exact: true }).fill('*.log');
    assert.equal(await page.getByRole('button', { name: '解压匹配', exact: true }).isDisabled(), true);
    await page.locator('.file-entry').filter({ hasText: 'nested' }).click();
    assert.equal(await page.getByRole('button', { name: '解压', exact: true }).isDisabled(), true);
    await page.getByLabel('文件名匹配', { exact: true }).fill('signal.2026-10-15.001.gz');
    await page.getByLabel('搜索范围', { exact: true }).selectOption('folder');
    await page.getByPlaceholder('搜索全文关键词或正则表达式…').fill('ERROR*gzip*中文');
    await page.getByRole('button', { name: '搜索全文', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.batch-summary')?.textContent.includes('1/1') && !document.querySelector('.search-bar .primary').disabled);
    assert.equal(await page.locator('.search-results .result').count(), 1);
    assert.match(await page.locator('.search-results .result').textContent(), /gzip 中文/);
    assert.deepEqual(errors, []);
    await page.screenshot({ path: path.resolve(__dirname, '../docs/local-folder.png') });
    await app.close();
    app = await _electron.launch({ ...(process.env.VIEWER_TEST_EXECUTABLE ? { executablePath: process.env.VIEWER_TEST_EXECUTABLE, args: [] } : { args: ['.'] }), cwd: path.resolve(__dirname, '..'), env: { ...process.env, VIEWER_DATA_DIR: path.join(temp, 'config') } });
    const restartedPage = await app.firstWindow();
    const restored = await restartedPage.evaluate(file => window.viewer.openExtracted(file), extracted.localPaths[0]);
    assert.equal(restored.archive, path.join(root, 'signal.2026-10-15.001.gz'));
    assert.equal(restored.name, extracted.localPaths[0]);
    console.log('Local folder passed: directory browsing, plain/gzip view, filename filter, group search, local result jump, newly added files, source switching, cancel and root boundary.');
  } finally { if (app) await app.close(); await fs.rm(temp, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
