    await visible().locator('.shared-telnet-display:visible .xterm-helper-textarea').press('Enter');
    await page.keyboard.press('Enter');
    await visible().getByLabel('Telnet 连接状态', { exact: true }).filter({ hasText: '已连接' }).waitFor();
    assert.equal(await visible().getByRole('tab', { name: 'Telnet · Local echo', exact: true }).count(), 1);
    await visible().locator('.telnet-connection-actions').getByRole('button', { name: '断开', exact: true }).click();
    await visible().getByRole('tab', { name: '日志查看', exact: true }).click();
