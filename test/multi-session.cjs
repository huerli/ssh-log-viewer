      await window.viewer.saveTheme('light');
      await window.viewer.saveFeatureEnabled('ssh', true);
      await window.viewer.saveProfile({ name: 'SSH fixture', host: '127.0.0.1', port, username: 'tester', auth: 'password', password: 'fixture-password', rememberPassword: true, keyPath: '' });
