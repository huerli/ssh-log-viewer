    assert.equal(await visible().getByRole('tab').count(), 2);
    assert.equal(await visible().getByRole('button', { name: '关闭 日志查看', exact: true }).count(), 0);
    assert.equal(await visible().locator('.header-actions').getByRole('button', { name: /日志查看|SSH 输出|Telnet 输出/ }).count(), 0);
    await visible().getByRole('tab', { name: 'Telnet · Local echo', exact: true }).click();
