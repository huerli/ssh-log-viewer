    await page.keyboard.press('Enter');
    await visible().getByLabel('SSH 终端状态', { exact: true }).filter({ hasText: '已连接' }).waitFor();
    assert.equal(await visible().getByRole('tab').count(), 2, 'SSH Enter reconnect stays in the same tab');
    await visible().locator('.connection-actions').getByRole('button', { name: '断开', exact: true }).click();
    await visible().getByLabel('SSH 输入', { exact: true }).press('Enter');
