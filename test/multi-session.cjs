    await visible().getByLabel('Telnet 连接状态', { exact: true }).filter({ hasText: '已连接' }).waitFor();
    assert.equal(await visible().getByRole('tab', { name: 'Telnet · Local echo', exact: true }).count(), 1, 'connecting from another page reconnects the existing tab');
    await visible().getByLabel('Telnet 连接选择', { exact: true }).selectOption('local2');
    await visible().locator('.telnet-connection-actions').getByRole('button', { name: '连接', exact: true }).click();
