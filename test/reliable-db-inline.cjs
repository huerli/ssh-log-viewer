const { dropLocal } = require('./drop-local.cjs');
const { _electron } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { gzipSync } = require('node:zlib');
(async () => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'viewer-inline-db-'));
  let app;
  try {
    const bytes = Buffer.alloc(128, 255);
    bytes.writeUInt32LE(123, 0); bytes[4] = 254; bytes.writeUInt16LE(19, 6);
    bytes[8] = 0; bytes[9] = 0;
    bytes.writeUInt32LE(456, 12); bytes.writeUInt32LE(789, 16); bytes.writeUInt32LE(123456, 20);
    bytes.set([0x12, 0x34, 0x56], 24);
    const file = path.join(temp, 'alarm.gz'); await fs.writeFile(file, gzipSync(Buffer.concat(Array.from({ length: 105 }, () => bytes))));
    app = await _electron.launch({ args: ['.'], cwd: path.resolve(__dirname, '..'), env: { ...process.env, VIEWER_DATA_DIR: path.join(temp, 'config') } });
    const page = await app.firstWindow(); const errors = []; page.on('pageerror', e => errors.push(e.message));
    await dropLocal(page, file);
    await page.waitForFunction(() => document.querySelector('.reliable-inline [role=status]')?.textContent.includes('待确认 105'));
    assert.equal(await page.locator('.settings-backdrop .reliable-db').count(), 0);
    assert.match(await page.locator('.reliable-inline .reliable-table').innerText(), /告警/);
    assert.equal(await page.locator('.reliable-table tbody tr').count(), 105);
    assert.equal(await page.getByRole('button', { name: '下一页', exact: true }).count(), 0);
    assert.equal(await page.getByRole('columnheader', { name: '转换后的时间（本地）', exact: true }).count(), 1);
    assert.match(await page.locator('.reliable-table tbody tr').first().innerText(), /1970-01-0[23].*UTC[+-]/);
    const controls = await page.locator('.reliable-controls label').evaluateAll(labels => labels.map(label => ({ height: label.getBoundingClientRect().height, nowrap: getComputedStyle(label).whiteSpace })));
    assert.ok(controls.every(label => label.height < 60 && label.nowrap === 'nowrap'));
    await page.locator('.reliable-table tbody tr').last().scrollIntoViewIfNeeded();
    await page.getByRole('button', { name: '查看槽位 0x00' }).click();
    assert.match(await page.locator('.reliable-detail').innerText(), /12 34 56/);
    await page.getByLabel('DB 状态筛选').selectOption('ok');
    assert.equal(await page.locator('.reliable-table tbody tr').count(), 0);
    const whole = await fs.readFile(path.join(__dirname, 'fixtures/reliable-wholercd.bin'));
    const slot = Buffer.alloc(256, 255); whole.copy(slot);
    const wholeFile = path.join(temp, 'wholercd.gz');
    await fs.writeFile(wholeFile, gzipSync(Buffer.concat(Array.from({ length: 8185 }, () => slot))));
    await dropLocal(page, wholeFile);
    await page.waitForFunction(() => document.querySelectorAll('.reliable-table tbody tr').length === 8185);
    await page.locator('.reliable-table tbody tr').nth(15).click();
    await page.getByRole('region', { name: '记录详情', exact: true }).waitFor();
    assert.match(await page.locator('.reliable-fields').innerText(), /K9/);
    const bounds = await page.locator('.reliable-records').evaluate(element => {
      const container = element.getBoundingClientRect();
      const table = element.querySelector('.reliable-table').getBoundingClientRect();
      const detail = element.querySelector('.reliable-detail').getBoundingClientRect();
      return { containerBottom: container.bottom, tableBottom: table.bottom, detailTop: detail.top, detailBottom: detail.bottom, detailHeight: detail.height };
    });
    assert.ok(bounds.detailHeight > 100);
    assert.ok(bounds.detailTop >= bounds.tableBottom);
    assert.ok(bounds.detailBottom <= bounds.containerBottom + 1);
    await page.screenshot({ path: '/tmp/reliable-db-inline-detail.png' });
    await page.getByRole('button', { name: '关闭记录详情', exact: true }).click();
    assert.equal(await page.locator('.reliable-detail').count(), 0);
    const plain = path.join(temp, 'plain.log'); await fs.writeFile(plain, 'normal log preview\n');
    await dropLocal(page, plain);
    await page.getByText('normal log preview', { exact: true }).waitFor();
    assert.equal(await page.locator('.reliable-inline').count(), 0);
    assert.deepEqual(errors, []);
    console.log('Inline gzip DB preview and text fallback passed');
  } finally { await app?.close(); await fs.rm(temp, { recursive: true, force: true }); }
})().catch(e => { console.error(e); process.exitCode = 1; });
