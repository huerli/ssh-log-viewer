function fixture() {
  const header = Buffer.from('d4c3b2a1020004000000000000000000ffff000001000000', 'hex');
  const records = [];
  let sequence = 100;
  for (let i = 0; i < 3205; i++) {
    const body = Buffer.from(`packet-${i}`);
    const packet = Buffer.alloc(54 + body.length);
    packet.writeUInt16BE(0x0800, 12); packet[14] = 0x45;
    packet.writeUInt16BE(packet.length - 14, 16); packet[22] = 64; packet[23] = 6;
    Buffer.from([192, 168, 1, 10, 10, 0, 0, 1]).copy(packet, 26);
    packet.writeUInt16BE(12345, 34); packet.writeUInt16BE(8080, 36); packet.writeUInt32BE(sequence, 38); packet.writeUInt32BE(500, 42);
    packet[46] = i === 40 ? 0x10 : 0x50; packet[47] = i === 10 ? 0x14 : 0x18; packet.writeUInt16BE(i === 20 ? 0 : 4096, 48);
    body.copy(packet, 54); sequence += body.length;
    const record = Buffer.alloc(16); record.writeUInt32LE(100 + i, 0); record.writeUInt32LE(packet.length, 8); record.writeUInt32LE(packet.length + (i === 30 ? 16 : 0), 12);
    records.push(record, packet);
  }
  return Buffer.concat([header, ...records]);
}
