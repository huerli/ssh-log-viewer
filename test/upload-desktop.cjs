const { _electron } = require('playwright');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { createServer } = require('./ssh-fixture.cjs');
(async () => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'viewer-upload-'));
  let app, server;
  try {
    const remote = path.join(temp, 'remote/system/log'), local = path.join(temp, 'local');
    await fs.mkdir(remote, { recursive: true }); await fs.mkdir(local);
    await fs.mkdir(path.join(temp, 'config'));
    await fs.writeFile(path.join(temp, 'config/settings.json'), JSON.stringify({ sshEnabled: true, telnetEnabled: false, autoCheckUpdates: false }));
    const file = path.join(local, '上传 中文.bin');
    const bytes = Buffer.from(Array.from({ length: 300000 }, (_, i) => i % 256));
    await fs.writeFile(file, bytes);
    const existing = path.join(local, 'existing.log'); await fs.writeFile(existing, 'new data');
    await fs.writeFile(path.join(remote, 'existing.log'), 'keep original');
    server = await createServer(path.join(temp, 'remote'));
    app = await _electron.launch({ args: ['.'], env: { ...process.env, VIEWER_DATA_DIR: path.join(temp, 'config') } });
    await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 1 }); });
    const page = await app.firstWindow();
    const ui = page.locator('.session-workspace:visible');
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    assert.equal(await ui.getByRole('button', { name: '上传', exact: true }).isDisabled(), true);
    await ui.locator('.connection-settings-toggle').click();
    await ui.getByLabel('主机', { exact: true }).fill('127.0.0.1');
    await ui.getByLabel('端口', { exact: true }).fill(String(server.port));
    await ui.getByLabel('用户名', { exact: true }).fill('tester');
    await ui.getByLabel('密码', { exact: true }).fill('fixture-password');
    await ui.getByRole('button', { name: '连接', exact: true }).click();
    await page.waitForFunction(() => { const b = [...document.querySelectorAll('.connection-actions button')].find(b => b.textContent === '断开'); return b && !b.disabled; });
    await ui.locator('.file-entry').filter({ hasText: 'existing.log' }).waitFor();
    await app.evaluate(({ dialog }, files) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: files }); }, [existing, file]);
    await ui.getByRole('button', { name: '上传', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.task-card')?.textContent.includes('上传 · 完成'));
    assert.deepEqual(await fs.readFile(path.join(remote, path.basename(file))), bytes);
    assert.equal(await fs.readFile(path.join(remote, 'existing.log'), 'utf8'), 'keep original');
    await ui.locator('.header-actions').getByRole('button', { name: '设置', exact: true }).click();
    await ui.locator('label.feature-toggle').filter({ has: page.getByLabel('强制覆盖', { exact: true }) }).click();
    assert.equal(await ui.getByLabel('强制覆盖', { exact: true }).evaluate(e => e.checked), true);
    await ui.getByRole('button', { name: '完成', exact: true }).click();
    const sourceId = (await ui.locator('[id$="-ssh-display-slot"]').getAttribute('id')).replace(/-ssh-display-slot$/, '');
    const forced = await page.evaluate(({ file, id }) => window.viewer.sessionInvoke(id, 'upload', ['/system/log', [file], true]), { file: existing, id: sourceId });
    assert.equal(forced.completedFiles, 1);
    assert.equal(await fs.readFile(path.join(remote, 'existing.log'), 'utf8'), 'new data');
    await ui.locator('.file-entry').filter({ hasText: path.basename(file) }).waitFor();
    assert.match(await ui.locator('.task-card').innerText(), /成功 1 · 失败 0/);
    assert.ok(server.requests.includes('WRITE'));
    await app.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }); });
    await ui.getByRole('button', { name: '上传', exact: true }).click();
    await page.waitForFunction(() => [...document.querySelectorAll('.file-actions button')].some(b => b.textContent === '上传' && !b.disabled));
    const dropped = path.join(local, '拖入上传.log'); await fs.writeFile(dropped, 'drop-upload-marker 中文\n');
    async function drop(files) {
      const cdp = await page.context().newCDPSession(page);
      const box = await ui.getByLabel('文件列表上传区域', { exact: true }).boundingBox();
      const data = { items: [], files, dragOperationsMask: 1 };
      for (const type of ['dragEnter', 'dragOver', 'drop']) await cdp.send('Input.dispatchDragEvent', { type, x: box.x + box.width / 2, y: box.y + box.height / 2, data });
      await cdp.detach();
    }
    await drop([dropped]);
    await ui.locator('.file-entry').filter({ hasText: '拖入上传.log' }).waitFor();
    assert.equal(await fs.readFile(path.join(remote, '拖入上传.log'), 'utf8'), 'drop-upload-marker 中文\n');
    const folder = path.join(local, '上传目录');
    await fs.mkdir(path.join(folder, 'nested'), { recursive: true });
    await fs.mkdir(path.join(folder, 'empty'));
    await fs.writeFile(path.join(folder, 'nested/a.log'), 'folder upload');
    await ui.getByRole('tab', { name: '日志查看', exact: true }).click();
    // CDP does not emit a drop for a directory on this Chromium build.
    // Exercise the same upload handler with a directory supplied by the picker.
    await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, folder);
    await ui.getByRole('button', { name: '上传', exact: true }).click();
    await ui.locator('.file-entry').filter({ hasText: '上传目录' }).waitFor();
    assert.equal(await fs.readFile(path.join(remote, '上传目录/nested/a.log'), 'utf8'), 'folder upload');
    assert.ok((await fs.stat(path.join(remote, '上传目录/empty'))).isDirectory());
    assert.deepEqual(errors, []);
    console.log('PASS: SFTP multi-file upload, binary/Chinese names, preserve existing files, refresh, picker cancellation, native drag upload');
  } finally { if (app) await app.close(); if (server) await server.close(); await fs.rm(temp, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
